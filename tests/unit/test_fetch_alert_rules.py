"""Unit tests for the changes tools/fetch-alert-rules.py makes to the upstream rules."""

import importlib.util
from pathlib import Path

import pytest
import yaml

_SCRIPT = Path(__file__).resolve().parents[2] / "tools" / "fetch-alert-rules.py"
_spec = importlib.util.spec_from_file_location("fetch_alert_rules", _SCRIPT)
fetch_alert_rules = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(fetch_alert_rules)

RulesError = fetch_alert_rules.RulesError


def _upstream():
    return {
        "groups": [
            {
                "name": "mgr",
                "rules": [
                    {"alert": "Inactive", "expr": "up{} == 0"},
                    {"alert": "Crash", "expr": "ceph_crash > 0"},
                ],
            },
            {"name": "cephadm", "rules": [{"alert": "Paused", "expr": "paused > 0"}]},
        ]
    }


_DROP = {"cephadm": "not used"}
_EXPRS = {"Inactive": ("up{} == 0", 'up{job=~".*_ceph_.*"} == 0')}


def test_drops_groups_and_rewrites_expressions():
    result = fetch_alert_rules.transform(_upstream(), _DROP, _EXPRS)
    assert [group["name"] for group in result["groups"]] == ["mgr"]
    assert result["groups"][0]["rules"][0]["expr"] == 'up{job=~".*_ceph_.*"} == 0'
    assert result["groups"][0]["rules"][1]["expr"] == "ceph_crash > 0"


def test_a_group_missing_upstream_fails():
    with pytest.raises(RulesError, match="groups to drop not found upstream: rgw"):
        fetch_alert_rules.transform(_upstream(), {**_DROP, "rgw": "no RGW"}, _EXPRS)


def test_a_changed_upstream_expression_fails():
    data = _upstream()
    data["groups"][0]["rules"][0]["expr"] = "up{job='ceph'} == 0"
    with pytest.raises(RulesError, match="Inactive: upstream expression is now"):
        fetch_alert_rules.transform(data, _DROP, _EXPRS)


def test_a_rule_missing_upstream_fails():
    with pytest.raises(RulesError, match="rules to rewrite not found upstream: Gone"):
        fetch_alert_rules.transform(_upstream(), _DROP, {**_EXPRS, "Gone": ("a", "b")})


def test_a_bare_up_left_upstream_fails():
    with pytest.raises(RulesError, match=r"Inactive: up\{\} matches every scrape job"):
        fetch_alert_rules.transform(_upstream(), _DROP, {})


def test_no_groups_fails():
    with pytest.raises(RulesError, match="no rule groups"):
        fetch_alert_rules.transform({}, {}, {})


def test_render_names_the_source_and_round_trips():
    data = fetch_alert_rules.transform(_upstream(), _DROP, _EXPRS)
    text = fetch_alert_rules.render("https://example.com/r.yaml", data, _DROP, _EXPRS)
    assert text.startswith("# Generated by tools/fetch-alert-rules.py")
    assert "# Source: https://example.com/r.yaml\n" in text
    assert "# Dropped group cephadm: not used\n" in text
    assert "# Rewritten expression: Inactive\n" in text
    assert yaml.safe_load(text) == data


def test_every_microceph_and_microovn_file_is_fetched():
    assert sorted(fetch_alert_rules.RULES) == ["microceph.rules", "microovn.rules"]
